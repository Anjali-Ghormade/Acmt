import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { connectDB } from './utils/db.js';
import auth from './routes/auth.js';
import publicRoutes from './routes/public.js';
import admin from './routes/admin.js';
const app=express();
app.disable('x-powered-by');
app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'}}));
const origins=(process.env.CLIENT_ORIGIN||'http://localhost:5173').split(',').map(x=>x.trim());
app.use(cors({origin:(origin,cb)=>!origin||origins.includes(origin)?cb(null,true):cb(new Error('Origin not allowed'))}));
app.use(express.json({limit:'100kb'}));
app.use('/api',rateLimit({windowMs:15*60*1000,limit:300}));
app.get('/api/health',(_req,res)=>res.json({status:'ok'}));
app.use('/api/auth',auth);app.use('/api/public',publicRoutes);app.use('/api/admin',admin);
app.use((req,res)=>res.status(404).json({message:'Route not found'}));
app.use((err,req,res,next)=>{if(res.headersSent)return next(err);const status=err.status||500;if(status>=500)console.error(err.message);res.status(status).json({message:status>=500?'Unexpected server error':err.message});});
connectDB().then(()=>app.listen(process.env.PORT||5000,()=>console.log('API ready'))).catch(e=>{console.error(e.message);process.exit(1)});
